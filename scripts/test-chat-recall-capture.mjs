import assert from 'node:assert/strict'
import { parseRevokeMessage } from '../src/shared/revoke-message.ts'
import { presentMessage } from '../src/main/message-content.ts'
import { captureChatRecalls } from '../src/main/chat-recall-capture.ts'
import { emptyMonitor } from '../src/main/group-monitor.ts'
// Same structure as the reported notice: no target message ID, only content and revoke time.
const xml = '<?xml version="1.0"?><sysmsg type="revokemsg"><revokemsg><content>你撤回了一条消息</content><revoketime>1234567890</revoketime></revokemsg></sysmsg>'
assert.deepEqual(parseRevokeMessage(10000, xml), { notice: '你撤回了一条消息', targetId: undefined })
assert.equal(presentMessage(10000, xml, new Map()).text, '你撤回了一条消息')
assert.equal(presentMessage(10002, xml, new Map()).text, '你撤回了一条消息')
assert.equal(parseRevokeMessage(1, '请不要撤回这条消息'), undefined)
assert.equal(parseRevokeMessage(10000, '<sysmsg><content>成员加入</content></sysmsg>'), undefined)
assert.equal(parseRevokeMessage(10002, '<revokemsg><replacemsg><![CDATA[甲撤回了消息]]></replacemsg><newmsgid>88</newmsgid></revokemsg>').targetId, '88')
const state = emptyMonitor()
const conversation = messages => ({ id:'fictional@chatroom',name:'虚构群',type:'group',messages,time:'',preview:'',records:'1',range:'',day:'' })
const msg = (id, text, type=1, serverId='') => ({ id, text, messageType:type, createdAt:1000, time:'12:00', from:'me', serverId })
const initial = conversation([msg('1', '撤回前已读到的文字', 1, '88')])
captureChatRecalls(state, initial, 1100)
assert.equal(state.rooms[0].enabled, false, '正常读取会话即可捕获，不要求开启群监控')
assert.equal(state.events.length, 0, '自动捕获不应开启或产生监控事件')
const recalled = conversation([{ ...msg('1', '', 10000), ...presentMessage(10000, xml, new Map()) }])
captureChatRecalls(state, recalled, 1200)
assert.equal(recalled.messages[0].recall.original, '撤回前已读到的文字', '无目标 ID 的通知可以通过相同原记录 ID 关联')
assert.equal(recalled.messages[0].from, 'me')
const unknown = conversation([{ ...msg('unknown', '', 10000), ...presentMessage(10000, xml, new Map()) }])
captureChatRecalls(state, unknown, 1300)
assert.equal(unknown.messages[0].recall, undefined, '没有原记录时不能仅凭撤回时间猜测')
const targetState = emptyMonitor()
captureChatRecalls(targetState, conversation([msg('2', '另一条原文', 1, '99')]), 1100)
const separate = conversation([{ ...msg('3', '', 10002), ...presentMessage(10002, '<revokemsg><newmsgid>99</newmsgid><content>你撤回了一条消息</content></revokemsg>', new Map()) }])
captureChatRecalls(targetState, separate, 1200)
assert.equal(separate.messages[0].recall.original, '另一条原文')
assert.equal(state.events.length, 0)
console.log('聊天撤回捕获测试通过：实际格式 XML、正常同步自动捕获、无目标 ID 同行替换、服务端 ID 关联、无原文回退与监控隔离。')

// WeChat may delete the original row and insert a notice with BOTH identifiers changed.
const diffState = emptyMonitor()
captureChatRecalls(diffState, conversation([msg('10', '已在会话显示的原文', 1, '100')]), 2000)
const differentIds = conversation([{ ...msg('11', '', 10000, '101'), createdAt:2100, ...presentMessage(10000, xml, new Map()) }])
captureChatRecalls(diffState, differentIds, 2200)
assert.equal(differentIds.messages[0].recall, undefined, '双标识均变化时不根据唯一差异猜测原文')
assert.equal(diffState.events.length, 0)
const ambiguousState = emptyMonitor()
captureChatRecalls(ambiguousState, conversation([msg('20', '候选甲'),msg('21', '候选乙')]), 2000)
const ambiguousNotice = conversation([{...msg('22', '', 10000),...presentMessage(10000,xml,new Map())}])
captureChatRecalls(ambiguousState, ambiguousNotice, 2200)
assert.equal(ambiguousNotice.messages[0].recall, undefined)
assert.equal(ambiguousNotice.messages[0].revoke.unresolvedReason, 'unlinked')
const expiredState = emptyMonitor()
captureChatRecalls(expiredState, conversation([msg('30', '不能跨很长时间猜测')]), 2000)
const expiredNotice = conversation([{...msg('31', '', 10000),...presentMessage(10000,xml,new Map())}])
captureChatRecalls(expiredState, expiredNotice, 200000)
assert.equal(expiredNotice.messages[0].recall,undefined)
const pageState = emptyMonitor()
const page=Array.from({length:60},(_,i)=>({...msg(String(100+i),'分页原文'+i),createdAt:i*1000}))
captureChatRecalls(pageState,conversation(page),60000)
const nextPage=[...page.slice(1),{...msg('160','',10000),createdAt:61000,...presentMessage(10000,xml,new Map())}]
const pageConversation=conversation(nextPage)
captureChatRecalls(pageState,pageConversation,62000)
assert.equal(pageConversation.messages.at(-1).recall,undefined,'不能把滚出最近 60 条范围的旧消息误判为撤回')
const ackState = emptyMonitor()
captureChatRecalls(ackState,conversation([msg('200','发送中的原文',1,'0')]),2000)
captureChatRecalls(ackState,conversation([msg('200','发送中的原文',1,'900')]),2100)
assert.equal(ackState.rooms[0].messages[0].serverId,'900','发送成功后的服务端标识必须回填')
const serverNotice=conversation([{...msg('201','',10000,'900'),...presentMessage(10000,xml,new Map())}])
captureChatRecalls(ackState,serverNotice,2200)
assert.equal(serverNotice.messages[0].recall.original,'发送中的原文')
console.log('标识变化回归通过：双 ID 改变拒绝猜测、发送确认回填、服务端行标识关联、多候选/跨页/过期拒绝误配。')
const {capturePreparedMedia}=await import('../src/main/chat-recall-capture.ts')
const mediaState=emptyMonitor()
captureChatRecalls(mediaState,conversation([msg('voice','[语音]',34,'voice-server')]),5000)
capturePreparedMedia(mediaState,'fictional@chatroom',{...msg('voice','[语音]',34,'voice-server'),voice:{hex:'010203'}},9000)
assert.equal(mediaState.rooms[0].checkedAt,5000,'读取旧媒体不推进实时捕获时间水位')
assert.equal(mediaState.rooms[0].messages[0].media.voice.hex,'010203')
const mediaNotice=conversation([{...msg('voice','撤回',10000),...presentMessage(10000,xml,new Map())}])
captureChatRecalls(mediaState,mediaNotice,10000)
assert.equal(mediaNotice.messages[0].recall.media.voice.hex,'010203')
console.log('已读取媒体捕获通过：语音原文保留、不推进同步水位、不发送监控事件')
const imageState=emptyMonitor(),imageId='a'.repeat(64)
capturePreparedMedia(imageState,'fictional@chatroom',{...msg('image','[图片]',3,'image-server'),image:{source:'wetrace-media://preview/'+imageId}},5000,()=>({data:Buffer.from('synthetic-image-bytes'),mime:'image/png'}))
assert.match(imageState.rooms[0].messages[0].media.image.source,/^data:image\/png;base64,/,'将已捕获图片字节存入加密状态，不只保存可失效的临时URL')
console.log('图片撤回留存通过：已读图片独立快照，不依赖临时预览缓存')
const collisionState=emptyMonitor()
captureChatRecalls(collisionState,conversation([msg('999','本地编号碰巧相同的其他消息',1,'111')]),1000)
const collisionNotice=conversation([{...msg('1000','',10002),...presentMessage(10002,'<revokemsg><newmsgid>999</newmsgid></revokemsg>',new Map())}])
captureChatRecalls(collisionState,collisionNotice,2000)
assert.equal(collisionNotice.messages[0].recall,undefined,'服务端目标编号不能回退匹配碰巧相同的本地编号')
