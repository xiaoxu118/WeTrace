// Synthetic conversations and statistics; no WeChat data or model calls.
const { app, BrowserWindow } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')
app.on('window-all-closed', () => {})
app.whenReady().then(async () => {
  const reference = await fs.readFile('scripts/test-report-ui.cjs', 'utf8')
  const begin = reference.indexOf('await fs.writeFile(preload, `') + 'await fs.writeFile(preload, `'.length
  const end = reference.indexOf('\n`)', begin)
  const source = reference.slice(begin, end).replace("contextBridge.exposeInMainWorld('wetrace', api)", `
let patternReads = 0, speechReads = 0
const analysisQueries = []
data.conversations.push({ ...data.conversations[0], id: 'friend', name: '测试联系人', type: 'friend' })
api.queryReportMessages = async query => { patternReads++; analysisQueries.push(query); return { ok: true, data: { ...query, messages: data.conversations[0].messages, counts: {} } } }
api.querySpeechStats = async query => { speechReads++; analysisQueries.push(query); return { ok: true, data: { total: 3, members: [{ id: 'a', name: '成员甲', count: 3 }], silentMembers: [{ id: 'b', name: '成员乙', count: 0 }] } } }
api.getAnalysisReads = async () => ({ patternReads, speechReads, analysisQueries })
contextBridge.exposeInMainWorld('wetrace', api)
`)
  await fs.mkdir('.cache', { recursive: true })
  const preload = path.resolve('.cache/chat-analysis-ui-preload.cjs')
  await fs.writeFile(preload, source)
  const window = new BrowserWindow({ show: false, width: 1280, height: 900, webPreferences: { preload, sandbox: false, offscreen: true } })
  try {
    await window.loadFile(path.resolve('out/renderer/index.html'))
    const run = async code => { try { return await window.webContents.executeJavaScript(code) } catch (error) { throw new Error(code + ': ' + error.message) } }
    const until = async code => { for (let i = 0; i < 80; i++) { if (await run(code)) return; await new Promise(resolve => setTimeout(resolve, 100)) }; throw new Error('UI timeout: ' + code + '\n' + await run('document.body.innerText')) }
    const open = () => run(`Array.from(document.querySelectorAll('.chat-head .ops button')).find(button => button.textContent === '聊天分析').click()`)
    await until(`!!document.querySelector('.chat-head')`)
    assert.equal(await run(`Array.from(document.querySelectorAll('.chat-head .ops button')).filter(button => ['聊天脉络', '发言分析'].includes(button.textContent)).length`), 0)
    await open()
    await until(`!!document.querySelector('.chat-analysis-modal [role="tab"]') && !!document.querySelector('.patterns-body .analysis-filters')`)
    assert.equal(await run(`document.querySelectorAll('[role="dialog"]').length`), 1, '只打开一个分析弹窗')
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.chat-analysis-modal [role="tab"]')).map(tab => tab.textContent)`), ['聊天脉络', '发言分析'])
    assert.equal((await run(`window.wetrace.getAnalysisReads()`)).speechReads, 0, '发言统计按需加载')
    const initialReads = (await run(`window.wetrace.getAnalysisReads()`)).patternReads
    const today = await run(`(() => { const now = new Date(); return [now.getFullYear(), String(now.getMonth() + 1).padStart(2, '0'), String(now.getDate()).padStart(2, '0')].join('-') })()`)
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.patterns-body .ant-picker input')).map(input => input.value)`), [today, today], '默认只查看今天')
    assert.equal(await run(`document.querySelector('.patterns-body .analysis-presets button[aria-pressed="true"]').textContent`), '今天')
    await run(`document.querySelector('.patterns-body .ant-select .ant-select-content').dispatchEvent(new MouseEvent('mousedown', { bubbles: true }))`)
    await until(`!!document.querySelector('.ant-select-dropdown:not(.ant-select-dropdown-hidden)')`)
    await run(`document.querySelector('.ant-select-item-option[title="成员甲"]').click()`)
    await until(`document.querySelector('.patterns-body .ant-select').textContent.includes('成员甲')`)
    await run(`document.querySelector('.patterns-body .ant-picker input').click()`)
    await until(`!!document.querySelector('.ant-picker-dropdown:not(.ant-picker-dropdown-hidden)')`)
    await run(`Array.from(document.querySelectorAll('.patterns-body .analysis-presets button')).find(button => button.textContent === '近 90 天').click()`)
    const selectedStart = await run(`document.querySelector('.patterns-body .ant-picker input').value`)
    assert.notEqual(selectedStart, today)
    await run(`Array.from(document.querySelectorAll('.chat-analysis-modal [role="tab"]')).find(tab => tab.textContent === '发言分析').click()`)
    await until(`!!document.querySelector('.speech-ranking')`)
    assert.ok((await run(`window.wetrace.getAnalysisReads()`)).speechReads >= 1)
    await run(`Array.from(document.querySelectorAll('.speech-tabs .ant-segmented-item')).find(button => button.textContent === '未发言成员').click()`)
    await until(`document.querySelector('.speech-ranking')?.textContent.includes('成员乙')`)
    await run(`Array.from(document.querySelectorAll('.chat-analysis-modal [role="tab"]')).find(tab => tab.textContent === '聊天脉络').click()`)
    assert.equal(await run(`document.querySelector('.patterns-body .ant-picker input').value`), selectedStart, '切换标签保留筛选条件')
    await run(`Array.from(document.querySelectorAll('.patterns-body .analysis-presets button')).find(button => button.textContent === '今天').click()`)
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.patterns-body .ant-picker input')).map(input => input.value)`), [today, today], '今天快捷选项重置日期范围')
    assert.equal((await run(`window.wetrace.getAnalysisReads()`)).patternReads, initialReads, '切回已加载的标签不重复读取')
    assert.ok((await run(`window.wetrace.getAnalysisReads()`)).analysisQueries.every(query => query.root === '/test' && query.conversationId === 'test@chatroom'))
    await run(`new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))`)
    await run(`new Promise(resolve => setTimeout(resolve, 300))`)
    await fs.mkdir('.screenshots', { recursive: true })
    await fs.writeFile('.screenshots/chat-analysis-tabs.png', (await window.webContents.capturePage()).toPNG())
    await run(`document.querySelector('.chat-analysis-modal .ant-modal-close').click()`)
    await until(`!document.querySelector('.chat-analysis-modal')`)
    await run(`Array.from(document.querySelectorAll('[aria-label="会话类型"] button')).find(button => button.textContent === '联系人').click()`)
    await until(`document.querySelector('.chat-head').textContent.includes('测试联系人')`)
    await open()
    await until(`!!document.querySelector('.chat-analysis-modal [role="tab"]')`)
    assert.deepEqual(await run(`Array.from(document.querySelectorAll('.chat-analysis-modal [role="tab"]')).map(tab => tab.textContent)`), ['聊天脉络'])
    assert.equal(await run(`document.documentElement.scrollWidth <= innerWidth`), true)
    console.log('聊天分析界面测试通过：合并入口、群聊双标签、联系人单标签、按需加载、筛选保留、今天默认及快捷选项、组件库弹层、会话隔离及关闭弹窗。')
  } finally { window.destroy(); await fs.rm(preload, { force: true }) }
}).then(() => app.exit(0)).catch(error => { console.error(error); app.exit(1) })
