import assert from 'node:assert/strict'
import { AiChatJobs } from '../src/main/ai-chat-jobs.ts'
const jobs=new AiChatJobs()
const a=jobs.start(1,'request-a','chat-a')
const b=jobs.start(1,'request-b','chat-b')
assert.throws(()=>jobs.start(1,'request-c','chat-a'),/该对话已有/)
assert.throws(()=>jobs.start(1,'request-a','chat-c'),/该对话已有/)
const other=jobs.start(2,'request-a','chat-a')
jobs.cancel(2,'request-b')
assert.equal(b.signal.aborted,false,'another window cannot cancel this request')
jobs.cancel(1,'request-a')
assert.equal(a.signal.aborted,true)
assert.equal(b.signal.aborted,false,'cancelling one chat leaves the other running')
jobs.finish(1,'request-a')
const restarted=jobs.start(1,'request-c','chat-a')
jobs.finish(1,'request-b')
assert.equal(restarted.signal.aborted,false)
jobs.cancelOwner(1)
assert.equal(restarted.signal.aborted,true)
assert.equal(other.signal.aborted,false,'closing one window leaves other owners running')
jobs.finish(1,'request-c')
jobs.cancelOwner(2)
assert.equal(other.signal.aborted,true)
console.log('AI并行任务：独立会话、重复发送防护、单任务取消、窗口隔离与退出清理通过')
